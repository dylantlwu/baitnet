/**
 * What happens to data/ when the demo starts.
 *
 * The local chain is rebuilt on every run, so only state that is bound to that
 * chain is cleared. Everything an expert produced (training DB, arena sessions,
 * evidence, eval reports, exports) is kept, and the training DB is backed up
 * on every start.
 *
 *   resetChainState()  every sandbox / memory run (not testnet: that chain persists)
 *   backupTraining()   every run → data/backups/training-<ts>.sqlite, newest 10 kept
 *   wipeAll()          `pnpm demo --fresh` only (after a backup); keeps evidence/.key and backups/
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { DATA_DIR, ROOT, c, errMsg, log } from "./util.ts";

/**
 * Files/dirs in data/ that reference the previous chain (alert ids, tx hashes, account
 * code hashes, RPC URL, keys) and are regenerated by the demo flow. Audited against
 * every dataPath(...) in apps/ and packages/ on 2026-11-09.
 */
export const CHAIN_BOUND = [
  "runtime.json", //         RPC URL + throw-away sandbox keys
  "memory-registry.json", // in-memory registry (fallback mode) — alert ids
  "reports.json", //         alertId + txHash of each on-chain report
  "events.jsonl", //         GuardEvents carrying AlertViews (ids, tx hashes)
  "flows.json", //           fund-flow graphs keyed by alertId
  "ack-receipts.json", //    responder acks (alertId, tx)
  "review-log.jsonl", //     review decisions of the demo's alert drafts
  "code-hashes.json", //     NEAR RPC code hashes of sandbox accounts
];

/** Kept on a normal start (listed so the README and the log can say so). */
export const KEPT = [
  "training.sqlite (+ -wal / -shm)",
  "arena/sessions/",
  "evidence/",
  "eval/",
  "training-export/",
  "conversations/",
  "backups/",
];

export const BACKUP_DIR = join(DATA_DIR, "backups");
const TRAINING_DB = join(DATA_DIR, "training.sqlite");
const KEEP_BACKUPS = Number(process.env.BAITNET_BACKUPS_KEEP || 10);

export function resetChainState() {
  if (!existsSync(DATA_DIR)) return;
  const removed = CHAIN_BOUND.filter((f) => existsSync(join(DATA_DIR, f)));
  for (const f of removed) rmSync(join(DATA_DIR, f), { recursive: true, force: true });
  if (removed.length) log.info(c.dim(`链每次重建：已清掉上一轮与链绑定的状态（${removed.join(", ")}）；训练数据、会话、证据都保留`));
}

function stamp(): string {
  return new Date().toISOString().replace(/[-:]/g, "").replace("T", "-").slice(0, 15); // 20261109-153012
}

/**
 * Consistent copy of data/training.sqlite (WAL included) via `VACUUM INTO`, which is
 * safe even while a server still has the DB open. Falls back to copying the file trio.
 */
export async function backupTraining(reason = "start"): Promise<string | undefined> {
  if (!existsSync(TRAINING_DB)) return undefined;
  mkdirSync(BACKUP_DIR, { recursive: true });
  let dest = join(BACKUP_DIR, `training-${stamp()}.sqlite`);
  for (let i = 1; existsSync(dest); i++) dest = join(BACKUP_DIR, `training-${stamp()}-${i}.sqlite`);
  try {
    const { DatabaseSync } = await import("node:sqlite");
    const db = new DatabaseSync(TRAINING_DB, { readOnly: true });
    try {
      db.exec(`VACUUM INTO '${dest.replace(/'/g, "''")}'`);
    } finally {
      db.close();
    }
  } catch (err) {
    log.warn(`VACUUM INTO 备份失败（${errMsg(err)}），改为直接复制文件`);
    copyFileSync(TRAINING_DB, dest);
    for (const ext of ["-wal", "-shm"]) if (existsSync(TRAINING_DB + ext)) copyFileSync(TRAINING_DB + ext, dest + ext);
  }
  pruneBackups();
  log.info(c.dim(`训练库已备份（${reason}）→ ${relative(ROOT, dest)}（保留最近 ${KEEP_BACKUPS} 份）`));
  return dest;
}

function pruneBackups() {
  const files = readdirSync(BACKUP_DIR)
    .filter((f) => /^training-.*\.sqlite$/.test(f))
    .map((f) => ({ f, t: statSync(join(BACKUP_DIR, f)).mtimeMs }))
    .sort((a, b) => b.t - a.t);
  for (const { f } of files.slice(KEEP_BACKUPS)) {
    for (const ext of ["", "-wal", "-shm"]) rmSync(join(BACKUP_DIR, f + ext), { force: true });
  }
}

/** `--fresh`: delete everything in data/ except evidence/.key, backups/ and the PID file. */
export async function wipeAll() {
  if (!existsSync(DATA_DIR)) return;
  const victims = readdirSync(DATA_DIR).filter((n) => n !== "backups" && n !== ".demo-pids.json");
  console.log(c.red(c.bold("\n  ⚠ --fresh：将彻底清空 data/（训练库、arena 会话、证据、评测报告、导出全部删除）")));
  console.log(c.red(`    要删除：${victims.join(", ") || "(空)"}`));
  console.log(c.red("    保留：evidence/.key（证据加密密钥）、backups/（含马上做的这份备份）"));
  const backup = await backupTraining("--fresh 之前");
  if (backup) console.log(c.yellow(`    恢复方法：停掉 demo 后 cp ${relative(ROOT, backup)} data/training.sqlite && rm -f data/training.sqlite-wal data/training.sqlite-shm`));
  if (process.stdout.isTTY) {
    for (let s = 5; s > 0; s--) {
      process.stdout.write(`\r    ${s}s 后开始删除，按 Ctrl-C 取消… `);
      await new Promise((r) => setTimeout(r, 1000));
    }
    process.stdout.write("\n");
  }
  for (const n of victims) {
    const p = join(DATA_DIR, n);
    if (n === "evidence") {
      for (const f of readdirSync(p)) if (f !== ".key") rmSync(join(p, f), { recursive: true, force: true });
    } else rmSync(p, { recursive: true, force: true });
  }
  log.ok("data/ 已清空（保留 evidence/.key 和 backups/）");
}
